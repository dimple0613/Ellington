const line = (doc: jsPDF, x: number, y: number, w: number, color: [number, number, number]) => {
  doc.setDrawColor(color[0], color[1], color[2]);
  doc.setLineWidth(0.4);
  doc.line(x, y, x + w, y);
};

function docBase(sub: string): jsPDF {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  doc.setFillColor(20, 22, 31);
  doc.rect(0, 0, pageW, 34, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Ellington ERP", 14, 16);
  doc.setFontSize(10.5);
  doc.setTextColor(200, 202, 212);
  doc.setFont("helvetica", "normal");
  doc.text(sub, 14, 24);
  return doc;
}

function docFooter(doc: jsPDF, subject: string) {
  const pageSize = doc.internal.pageSize;
  const pageH = pageSize.getHeight();
  const pageW = pageSize.getWidth();
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(160, 163, 175);
    doc.setFont("helvetica", "normal");
    doc.text("Ellington ERP · " + subject, 14, pageH - 6);
    doc.text("Page " + i + " of " + pageCount, pageW - 14, pageH - 6, { align: "right" });
  }
}

