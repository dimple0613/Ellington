function soaNumbers(u: UnitDoc) {
  const NET_DISCOUNT = 0.05;
  const net = Math.round(u.price * (1 - NET_DISCOUNT));
  const collected = Math.round(net * 0.62);
  const outstanding = net - collected;
  return { net, collected, outstanding };
}

