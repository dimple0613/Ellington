const AED = "AED ";
const fmt = (n: number) => n.toLocaleString("en-US");

const fmtDate = (d: Date) => d.toLocaleDateString("en-US", { day: "2-digit", month: "short", year: "numeric" });
const todayStr = () => fmtDate(new Date());

function watermark(doc: jsPDF, text: string) {
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  doc.saveGraphicsState();
  doc.setGState(new GState({ opacity: 0.12 }));
  doc.setFont("helvetica", "bold");
  doc.setFontSize(40);
  doc.setTextColor(20, 22, 31);
  doc.text(text, pageW / 2, pageH / 2, { align: "center", angle: 40 });
  doc.restoreGraphicsState();
}

function downloadBlob(doc: jsPDF, filename: string) {
  const blob = doc.output("blob");
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

