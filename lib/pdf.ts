function soaNumbers(u: UnitDoc, opts?: { discountPct?: number; collected?: number }) {
  // B-01: figures come from caller data. Nothing is fabricated in the PDF —
  // a missing discount is treated as 0% and missing collections as AED 0.
  const discountPct = opts?.discountPct ?? 0;
  const net = Math.round(u.price * (1 - discountPct / 100));
  const collected = Math.round(opts?.collected ?? 0);
  const outstanding = Math.max(0, net - collected);
  return { net, collected, outstanding, discountPct };
}

