  const paidRe = /paid|cleared|settled|credited|received/i;
  const collectedCalc = milestones
    .filter((m) => paidRe.test(m.status))
    .reduce((a, m) => a + (Number(String(m.amount).replace(/[^0-9.]/g, "")) || 0), 0);
  const paid = new Set(milestones.filter((m) => paidRe.test(m.status)).map((m) => m.label));
  const { net, collected, outstanding, discountPct } = soaNumbers(u, { discountPct: opts?.discountPct, collected: opts?.collected ?? collectedCalc });
  const buyerName = u.buyer === "—" ? "Unassigned" : u.buyer;
  const today = new Date();
  const nextDueRow = milestones.find((m) => !paid.has(m.label) && (!m.due || new Date(m.due) >= today));
  const nextDue = nextDueRow ? nextDueRow.due : "—";

  let y = 46;
  doc.setTextColor(20, 22, 31);
